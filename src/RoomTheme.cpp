const ThemeStyle& GetThemeStyle(RoomTheme theme) { return kThemes[static_cast<int>(theme)].style; }

bool ParseRoomTheme(const std::string& text, RoomTheme& out)
{
    for (int i = 0; i < static_cast<int>(std::size(kThemes)); ++i)
    {
        if (text == kThemes[i].key)
        {
            out = static_cast<RoomTheme>(i);
            return true;
        }
    }
    return false;
}
